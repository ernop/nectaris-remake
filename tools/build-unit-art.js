#!/usr/bin/env node
'use strict';
const fs=require('fs'),path=require('path');
const A=require('../art/units/pixel-art.js');
const TYPES=require('../js/data-units.js').UNIT_TYPES;
const {png,text,C}=require('./pixel-art-export.js');
const OUT=path.join(__dirname,'../art/units/output');fs.mkdirSync(OUT,{recursive:true});
const descriptions={
 CHARLIE:'Small rifleman; field helmet and level rifle',
 KILROY:'Small infantryman with a shoulder launcher',
 PANTHER:'Small rider on a low two-wheel motorcycle',
 BISON:'Low rectangular turret and long single gun',
 LENET:'Compact chassis with two staggered scout turrets',
 POLAR:'Heavy slab skirts and offset rectangular turret',
 GRIZZLY:'Rear angular turret and extended cannon',
 SLAGGER:'Hover wedge, engine slots and an open underside',
 TITAN:'Tall square mantlet and two-tube side pod',
 GIANT:'Wide armored hull, twin guns and rear cupola',
 EAGLE:'Straight wings, small pods and carried bombs',
 FALCON:'Rear delta wings and an extended bare nose',
 HUNTER:'Twin engine nacelles and wing-tip missiles',
 HADRIAN:'Raised long gun on a flat tracked carriage',
 OCTOPUS:'Rectangular rocket box with six tube mouths',
 ATLAS:'Static gun on four open stabilizer legs',
 RABBIT:'Small wheeled chassis with two short missiles',
 LYNX:'Long missile rail and separate rear sensor',
 SEEKER:'Two separated elevated anti-aircraft barrels',
 HAWKEYE:'Angular radar dish and paired missile bank',
 MULE:'Cargo box, forward cab and three axle groups',
 PELICAN:'Crossed rotor, tail boom and cargo fuselage',
 TRIGGER:'Low pressure plate and perimeter prongs'
};
const frames={},report=[],colors={};
for(const faction of ['union','xenon','attack','neutral'])colors[faction]=A.palette(faction);
const ids=Object.keys(TYPES),fingerprints=new Set();
if(ids.length!==23)throw Error('Review the export contract when changing the stock roster');
for(const id of ids){
 frames[id]={};
 for(const facing of ['right','left']){
  const s=A.sprite(id,facing),used=new Set();let minX=32,minY=32,maxX=-1,maxY=-1,count=0;
  if(s.w!==32||s.h!==32)throw Error(id+': wrong native frame size');
  for(let y=0;y<32;y++)for(let x=0;x<32;x++){
   const v=s.get(x,y);if(!v)continue;
   const dx=Math.abs(x+.5-16),dy=Math.abs(y+.5-16);
   if(!Number.isInteger(v)||v<1||v>15||dx>14||dy>14||dx+dy>22)throw Error(id+'/'+facing+': unsafe pixel '+x+','+y);
   used.add(v);count++;minX=Math.min(minX,x);maxX=Math.max(maxX,x);minY=Math.min(minY,y);maxY=Math.max(maxY,y);
  }
  if(!count||minX!==31-maxX)throw Error(id+'/'+facing+': empty or horizontally uncentered');
  if(TYPES[id].cls==='infantry'&&(maxY-minY+1>17||count>240))throw Error(id+': infantry must stay small');
  const rows=Array.from({length:32},(_,y)=>Array.from(s.p.slice(y*32,y*32+32),v=>v?v.toString(16):'.').join(''));
  frames[id][facing]=rows;
  const signature=rows.join('');
  if(facing==='right'){if(fingerprints.has(signature))throw Error(id+': duplicate sprite');fingerprints.add(signature);}
  report.push({id,facing,visibleBounds:[minX,minY,maxX-minX+1,maxY-minY+1],opaquePixels:count,paletteEntries:used.size});
  for(const state of ['union','xenon','attack','spent']){
   const image=A.colorize(s,state==='spent'?'union':state,state==='spent');
   png(image,path.join(OUT,id.toLowerCase()+'-'+state+'-'+facing+'.png'));
  }
 }
}
const data={frame:32,anchor:[16,16],light:'screen-upper-left',codes:'123456789abcdef',palettes:colors,descriptions,frames};
fs.writeFileSync(path.join(__dirname,'../js/data-unit-art.js'),'/* Generated by tools/build-unit-art.js from original pixel constructions. */\nvar NATIVE_UNIT_ART = '+JSON.stringify(data,null,2)+';\nif(typeof module!=="undefined")module.exports=NATIVE_UNIT_ART;\n');
const hex=(x,y)=>[[x-24,y],[x-8,y-16],[x+8,y-16],[x+24,y],[x+8,y+16],[x-8,y+16]];
for(const mode of ['faction','attack','spent']){
 const sheet=new A.Surface(548,480);sheet.rect(0,0,548,480,C('#14151f'));
 text(sheet,'23 UNITS / NATIVE 32 X 32 / '+mode.toUpperCase(),16,12,C('#c0e4f6'));
 ids.forEach((id,i)=>{
  const x=18+(i%6)*88,y=32+Math.floor(i/6)*112;
  text(sheet,id,x+9,y,C('#ecf4f0'));
  for(const [row,facing,faction] of [[0,'right','union'],[1,'left','xenon']]){
   const cx=x+32,cy=y+34+row*38;
   sheet.poly(hex(cx,cy),C('#482f36'));
   sheet.blit(A.colorize(A.sprite(id,facing),mode==='attack'?'attack':faction,mode==='spent'),cx-16,cy-16);
  }
 });
 png(sheet,path.join(OUT,mode==='faction'?'units-native.png':'units-'+mode+'-native.png'));
}
fs.writeFileSync(path.join(OUT,'manifest.json'),JSON.stringify({revision:5,style:'angular military',nativeFrame:[32,32],displayScale:1,horizontalAlignment:'opaque-bounds-centered',unitCount:ids.length,directionalFrames:report,exportedVariants:ids.length*8},null,2)+'\n');
console.log('Exported '+ids.length+' units, '+report.length+' directional frames and '+ids.length*8+' native PNG variants.');
